import assert from "node:assert/strict";
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { after, test } from "node:test";
import { makeSandbox, readFacts, runFacts } from "./helpers.mjs";

let loaded;

function servicesOf() {
  if (!loaded) {
    const sb = makeSandbox();
    const run = runFacts(sb);
    assert.equal(run.status, 0, run.output);
    loaded = { sb, services: readFacts(sb).pages["bazy-danych"].facts.services };
  }
  return loaded.services;
}

after(() => loaded?.sb.cleanup());

const service = (name) => servicesOf().find((s) => s.name === name);
const entity = (svc, table) => service(svc).entities.find((e) => e.table === table);
const byColumn = (columns) => [...columns].sort((a, b) => a.name.localeCompare(b.name));

function shapeOf(e) {
  return { table: e.table, key: e.key, columns: byColumn(e.columns), foreignKeys: e.foreignKeys, tenancy: e.tenancy };
}

test("the Bazy danych facts hold both Portfolio tables with columns, key and FK, tenancy filter on the IUserOwned entity", () => {
  assert.deepEqual(service("Portfolio").entities.map((e) => e.table).sort(), ["Assets", "MetalHoldings", "Portfolios"]);
  assert.deepEqual(entity("Portfolio", "MetalHoldings").foreignKeys, [{ column: "AssetId", references: "Assets" }]);
  assert.deepEqual(shapeOf(entity("Portfolio", "Assets")), {
    table: "Assets",
    key: ["Id"],
    columns: byColumn([
      { name: "Id", type: "Guid", nullable: false },
      { name: "PortfolioId", type: "Guid", nullable: false },
      { name: "Quantity", type: "decimal", nullable: false },
      { name: "Symbol", type: "string", nullable: true },
      { name: "UserId", type: "Guid", nullable: false },
    ]),
    foreignKeys: [{ column: "PortfolioId", references: "Portfolios" }],
    tenancy: "filtr tenancy",
  });
  assert.deepEqual(shapeOf(entity("Portfolio", "Portfolios")), {
    table: "Portfolios",
    key: ["Id"],
    columns: byColumn([
      { name: "Id", type: "Guid", nullable: false },
      { name: "Name", type: "string", nullable: false },
      { name: "UserId", type: "Guid", nullable: false },
    ]),
    foreignKeys: [],
    tenancy: "filtr tenancy",
  });
});

test("a UserId column without IUserOwned is marked UserId bez filtra on Identity's RefreshTokens", () => {
  assert.deepEqual(shapeOf(entity("Identity", "RefreshTokens")), {
    table: "RefreshTokens",
    key: ["Id"],
    columns: byColumn([
      { name: "ExpiresAt", type: "DateTimeOffset", nullable: false },
      { name: "Id", type: "Guid", nullable: false },
      { name: "TokenHash", type: "string", nullable: false },
      { name: "UserId", type: "Guid", nullable: false },
    ]),
    foreignKeys: [],
    tenancy: "UserId bez filtra",
  });
});

test("the MassTransit tables collapse into one outbox/inbox line per service and stay out of the entities", () => {
  assert.deepEqual(service("Portfolio").masstransit, {
    label: "outbox/inbox",
    tables: ["PortfolioInboxState", "PortfolioOutboxMessage", "PortfolioOutboxState"],
  });
  assert.ok(!service("Portfolio").entities.some((e) => e.table.includes("Outbox") || e.table.includes("Inbox")));
});

test("a model snapshot with no entity fails loudly naming the service and writes nothing", () => {
  const sandbox = makeSandbox();
  try {
    writeFileSync(
      path.join(sandbox.root, "services", "Identity", "Skarbiec.Identity", "Migrations", "IdentityDbContextModelSnapshot.cs"),
      "// <auto-generated />\nnamespace Skarbiec.Identity.Migrations\n{\n    partial class IdentityDbContextModelSnapshot\n    {\n        protected override void BuildModel(ModelBuilder modelBuilder)\n        {\n        }\n    }\n}\n",
    );
    const run = runFacts(sandbox);
    assert.notEqual(run.status, 0);
    assert.match(run.output, /Identity/);
    assert.ok(!existsSync(sandbox.out) || readdirSync(sandbox.out).length === 0, "out must stay empty");
  } finally {
    sandbox.cleanup();
  }
});
